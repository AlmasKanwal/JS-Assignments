// Select container
const productContainer = document.getElementById("productContainer");

// Generate card for each product
const generateProductCard = (product) => {
  return `
    <div class="card shadow-sm" style="width: 22rem;">
      <img src="${product.image}" class="card-img-top" alt="${product.title}">
      <div class="card-body">
        <h5 class="card-title">${product.title}</h5>
        <p class="card-text"><strong>Native Area:</strong> ${product.area}</p>
        <p class="card-text des">${product.description}</p>
        <p class="card-text"><strong>Price:</strong> $${product.price}</p>
        <a href="#" class="btn">Buy Now</a>
      </div>
    </div>
  `;
};

// Display all Cards
let productHTML = products.map(generateProductCard).join("");
productContainer.innerHTML = productHTML;

// Search Product
const searchProduct = (products, searchItem) => {
  let filteredProducts = products.filter((product) => {
    return product.title.toLowerCase().includes(searchItem.toLowerCase());
  });

  return filteredProducts;
}

// Search Input 
const searchInput = (searchItem) => {
  let searchResult = searchProduct(products, searchItem);
  if(searchResult.length > 0){
    let productHtml = searchResult.map(generateProductCard).join("");
    productContainer.innerHTML = productHtml;
  } else {
    productContainer.innerHTML = `<h1>No Match Found!</ h1>`
  }
}
